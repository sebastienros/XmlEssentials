namespace CloudNimble.Text.Xml.XPath
{

    /// <summary>
    /// The additive and multiplicative operators of XPath 1.0.
    /// </summary>
    internal enum XPathArithmeticOperator : byte
    {

        /// <summary><c>+</c>.</summary>
        Add,

        /// <summary><c>-</c>.</summary>
        Subtract,

        /// <summary><c>*</c>.</summary>
        Multiply,

        /// <summary><c>div</c>.</summary>
        Divide,

        /// <summary><c>mod</c>.</summary>
        Modulo,

    }

}
