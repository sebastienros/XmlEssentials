        [TestMethod]
        public void Variable_ExpandedName_IsTheValueSet()
        {
            var variables = new XPathVariables();
            variables.Set("v", 2, "urn:p");
            variables.Set("v", 10);
            XPathRendering.Evaluate(Main, "$p:v + 1", Context, Options, variables).Should().Be("3");
            XPathRendering.Evaluate(Main, "$v + 1", Context, Options, variables).Should().Be("11");
        }

