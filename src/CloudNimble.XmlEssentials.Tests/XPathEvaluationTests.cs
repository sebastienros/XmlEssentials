        [DataRow("1 | /r", "The operands of '|' must be node-sets.", 0)]
        [DataRow("/r | 'x' | /r", "The operands of '|' must be node-sets.", 5)]
        [DataRow("(1)[1]", "A predicate can only filter a node-set.", 1)]
        [DataRow("'a'[1]", "A predicate can only filter a node-set.", 0)]
        [DataRow("(1)/a", "A path can only continue from a node-set.", 1)]
        [DataRow("count(1)", "The argument of count() must be a node-set.", 6)]
        [DataRow("sum('1')", "The argument of sum() must be a node-set.", 4)]
        [DataRow("local-name(1)", "The argument of local-name() must be a node-set.", 11)]
        [DataRow("namespace-uri(true())", "The argument of namespace-uri() must be a node-set.", 14)]
        [DataRow("name('x')", "The argument of name() must be a node-set.", 5)]
        public void Evaluate_Error_ThrowsWithItsPosition(string expression, string message, int position)
        {
            var act = () => XPathRendering.Evaluate(Main, expression, Context, Options);
            var thrown = act.Should().Throw<XPathException>().Which;
            thrown.Message.Should().Be(message);
            thrown.Position.Should().Be(position);
